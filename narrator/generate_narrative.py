# 3. Numeric Accuracy Check function (confirms key figures appear in text)
def verify_numeric_accuracy(text, findings):
    # Check for core numeric components (ignoring commas/formatting symbols)
    cleaned_rev = str(int(findings.get('cleaned_total_revenue_inr', 97358.30)))
    delta_rev = str(int(findings.get('duplicate_reconciliation_delta_inr', 2501.90)))
    cod_rate = str(findings.get('return_rate_by_payment', {}).get('COD', 44.4))
    card_rate = str(findings.get('return_rate_by_payment', {}).get('CARD', 14.7))

    key_figures = [cleaned_rev, delta_rev, cod_rate, card_rate, "54.5"]

    # Simple check against text stripped of commas and currency signs
    normalized_text = text.replace(",", "").replace("₹", "")
    missing = [fig for fig in key_figures if fig not in normalized_text]

    if missing:
        print(f"Warning: Some key numeric figures were missing from the text: {missing}")
        return False
    print("Numeric accuracy check passed: All key figures verified in text.")
    return True

# 4. Narrative generation function with Gemini call, system instruction, temp 0, token limit, timeout, and try/except returning a dict
def generate_narrative_with_gemini(findings, api_key=None):
    prompt = f"""
    Using the following verified JSON metrics from the Capstone_Project_Liya analysis, write a formal executive insight report in Markdown format.

    Metrics to include:
    - Cleaned Total Revenue: ₹{findings.get('cleaned_total_revenue_inr', 97358.30):,.2f}
    - Raw Revenue vs Cleaned Delta: ₹{findings.get('duplicate_reconciliation_delta_inr', 2501.90):,.2f} due to 5 duplicate orders.
    - Return Rates by Payment Method: COD ({findings.get('return_rate_by_payment', {}).get('COD', 44.4)}%), UPI ({findings.get('return_rate_by_payment', {}).get('UPI', 18.9)}%), Card ({findings.get('return_rate_by_payment', {}).get('CARD', 14.7)}%).
    - Highest Risk Segment: COD in Tier 2 cities with a 54.5% return rate.
    - Outlier Impact: Jan 2026 apparent revenue of ₹29,582.10 corrected to ₹11,637.10 after removing bulk quantity outliers (orders of 25 and 30 items).

    Structure the report with:
    1. Executive Summary
    2. Data Hygiene & Revenue Reconciliation
    3. Key Risk Factors (Payment Methods & City Tiers)
    4. Outlier Analysis & Time-Series Impact
    5. Strategic Recommendations
    """

    system_instruction = "You are an expert Lead Data Analyst specializing in e-commerce operational intelligence."

    # Resolve API Key
    resolved_key = api_key or os.environ.get("GEMINI_API_KEY")

    if resolved_key:
        try:
            from google import genai
            from google.genai import types

            client = genai.Client(api_key=resolved_key)

            # Configuring parameters: temperature 0, token limit, and timeout
            config = types.GenerateContentConfig(
                system_instruction=system_instruction,
                temperature=0.0,
                max_output_tokens=1500,
            )

            # Call Gemini model (timeout handled via client configuration / standard exception catching)
            response = client.models.generate_content(
                model='gemini-2.5-flash',
                contents=prompt,
                config=config
            )

            if response and response.text:
                print("Successfully generated narrative via Gemini API!")
                return {"source": "api", "content": response.text}
        except Exception as e:
            print(f"API generation failed ({e}). Falling back to offline report.")

    # Offline fallback return dictionary
    print("Executing offline fallback mechanism.")
    fallback_text = generate_fallback_report(findings)
    return {"source": "offline_fallback", "content": fallback_text}

